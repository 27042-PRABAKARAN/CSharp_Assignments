namespace Calculator
{
    /// <summary>
    /// Represents the available menu choices for the calculator application.
    /// </summary>
    internal enum CalculatorOptions
    {
        /// <summary>
        /// The addition operation.
        /// </summary>
        Add = 1,

        /// <summary>
        /// The subtraction operation.
        /// </summary>
        Subtract,

        /// <summary>
        /// The multiplication operation.
        /// </summary>
        Multiply,

        /// <summary>
        /// The division operation.
        /// </summary>
        Divide,

        /// <summary>
        /// Exits the application.
        /// </summary>
        Exit,
    }
}